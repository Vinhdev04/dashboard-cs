/**
 * Hàm phụ trợ tính toán tỷ lệ thay đổi và xu hướng tăng/giảm giữa hai mốc số liệu
 * @param current Giá trị kỳ hiện tại
 * @param previous Giá trị kỳ trước
 * @returns Đối tượng kết quả gồm percent, trend ('up' | 'down' | 'equal') và label hiển thị
 */
function calculateTrendDiff(current: number, previous: number) {
  if (previous === 0) {
    return { percent: 0, trend: 'equal' as const, label: '0%' };
  }
  const diff = current - previous;
  const percent = Number(((diff / previous) * 100).toFixed(1));
  const absPercent = Math.abs(percent);

  if (diff > 0) {
    return { percent: absPercent, trend: 'up' as const, label: `↑ +${diff} (${absPercent}%)` };
  } else if (diff < 0) {
    return { percent: absPercent, trend: 'down' as const, label: `↓ -${Math.abs(diff)} (${absPercent}%)` };
  }
  return { percent: 0, trend: 'equal' as const, label: '0%' };
}

