  const maintCurrent = RAW_PROJECTS.filter((p) => p.type === 'maintenance').length;
  const maintPrev = maintCurrent;
  const maintDiff = calculateTrendDiff(maintCurrent, maintPrev);

  const newCurrent = RAW_PROJECTS.filter((p) => p.type === 'new').length;
  const newPrev = newCurrent - 1 > 0 ? newCurrent - 1 : 1;
  const newDiff = calculateTrendDiff(newCurrent, newPrev);

